"""
Synthetic placement dataset generator
=====================================
We do not have access to our college's real placement records, so this script
creates a SYNTHETIC dataset with the same fields the website collects. The
placement outcome is drawn from a noisy logistic rule, so the data behaves like
a realistic (but not real) campus: higher CGPA / skills / internships make
placement more likely, backlogs make it less likely, and there is randomness so
no model can reach 100% accuracy.

IMPORTANT: results trained on this file describe how well a model recovers the
rule written below - NOT how well it predicts real students. Say this in the
paper and the viva. Replace placement_data.csv with real records and re-run
train_model.py to get real numbers.

Usage:  python generate_dataset.py            (writes placement_data.csv + .meta.json)
"""
import json, os
import numpy as np
import pandas as pd

SEED = 7
N = 1500
rng = np.random.default_rng(SEED)
here = os.path.dirname(os.path.abspath(__file__))


def clip(a, lo, hi):
    return np.clip(a, lo, hi)


cgpa = clip(rng.normal(7.3, 0.9, N), 5.0, 10.0).round(2)
tenth = clip(rng.normal(78, 9, N), 50, 98).round(1)
twelfth = clip(0.5 * tenth + 0.5 * rng.normal(76, 10, N), 50, 98).round(1)
aptitude = clip(rng.normal(60, 15, N) + 4 * (cgpa - 7.3), 20, 100).round(0)
communication = clip(np.round(rng.normal(6, 1.7, N)), 1, 10).astype(int)
programming = clip(np.round(rng.normal(5.8, 2.0, N) + 0.8 * (cgpa - 7.3)), 1, 10).astype(int)
projects = clip(rng.poisson(2.0, N) + (programming >= 7), 0, 7)
internships = clip(rng.poisson(0.8, N), 0, 4)
certifications = clip(rng.poisson(1.5, N), 0, 6)
backlogs = clip(rng.poisson(np.where(cgpa < 6.5, 1.4, 0.3)), 0, 6)

# hidden "placement rule" (logit) + noise
z = (0.9 * (cgpa - 7.2) + 0.03 * (aptitude - 60) + 0.25 * (programming - 6)
     + 0.20 * (communication - 6) + 0.25 * projects + 0.5 * internships
     + 0.15 * certifications - 0.7 * backlogs + 0.01 * (twelfth - 75) + 0.2)
placed = rng.binomial(1, 1 / (1 + np.exp(-z)))

# salary (LPA = lakhs per annum) only for placed students
salary = (3.0 + 0.6 * (cgpa - 7) + 0.12 * (programming - 6) + 0.15 * projects
          + 0.25 * internships + 0.05 * communication + rng.normal(0, 0.6, N))
salary = np.where(placed == 1, clip(salary, 2.5, 20).round(2), np.nan)

df = pd.DataFrame(dict(cgpa=cgpa, tenth=tenth, twelfth=twelfth, aptitude=aptitude,
                       communication=communication, programming=programming,
                       projects=projects, internships=internships,
                       certifications=certifications, backlogs=backlogs,
                       placed=placed, salary=salary))
df.to_csv(os.path.join(here, '..', 'placement_data.csv'), index=False)
json.dump({'source': 'synthetic', 'rows': N, 'seed': SEED,
           'note': 'Generated by ml/data/generate_dataset.py - not real student data.'},
          open(os.path.join(here, '..', 'placement_data.csv.meta.json'), 'w'), indent=2)
print(f'Wrote {N} synthetic rows. Placed share: {placed.mean():.1%}')
